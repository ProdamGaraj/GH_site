/**
 * Единицы измерения MacroCRM v2.
 *
 * Цены API отдаёт в МИНИМАЛЬНЫХ единицах валюты (тийины для UZS), площади —
 * в квадратных метрах как есть. Проверено на живых данных: квартира 5139781
 * имеет price 115377956200 и areaTotal 55.63, что даёт priceM2 2074024019 —
 * то есть 20 740 240.19 сум за метр. Делитель ровно 100.
 *
 * Функции живут отдельным модулем, потому что делят цену два независимых
 * потребителя — агрегатор статистики ЖК и маппер квартир. Второе деление,
 * написанное по месту, разошлось бы с первым на порядок и молча.
 */

/** Тийины/копейки → сумы/рубли. */
const MINOR_UNITS_PER_MAJOR = 100

/**
 * Цена из минимальных единиц в основные.
 *
 * Ноль и отрицательные значения — это «цены нет», а не «цена ноль»: в CRM так
 * помечены объекты без прайса, и показывать «0 сум» на карточке нельзя.
 */
export function priceFromMinorUnits(value: unknown): number | null {
  const n = Number(value)
  if (!Number.isFinite(n) || n <= 0) return null
  return Math.round(n / MINOR_UNITS_PER_MAJOR)
}

/** Площадь с округлением до сотых: разница в 0.01 м² у них значима. */
export function areaOrNull(value: unknown): number | null {
  const n = Number(value)
  if (!Number.isFinite(n) || n <= 0) return null
  return Math.round(n * 100) / 100
}
