/**
 * Человеческие описания сбоев запроса.
 *
 * Раньше любой ответ с не-JSON телом превращался в литерал «Network error» —
 * а именно так отвечает nginx, когда бэкенд лежит (502 с HTML-страницей).
 * Пользователь на форме логина видел «сетевую ошибку» при работающей сети и
 * шёл проверять интернет вместо контейнера. Сообщение должно называть причину.
 */

/** Статус, которым помечаем запрос, не доехавший до сервера. */
export const NETWORK_FAILURE_STATUS = 0

/**
 * Описание по HTTP-статусу — для ответов, у которых тело не JSON
 * (страницы ошибок nginx, пустые ответы прокси).
 */
export function describeHttpFailure(status: number): string {
  if (status === 502 || status === 503 || status === 504) {
    return `Сервер CMS не отвечает (HTTP ${status}). Похоже, бэкенд не запущен — проверьте контейнер.`
  }
  if (status === 401) return 'Требуется вход: сессия не найдена или истекла.'
  if (status === 403) return 'Недостаточно прав для этого действия.'
  if (status === 404) return 'Адрес не найден на сервере (HTTP 404).'
  if (status === 413) return 'Файл слишком большой для загрузки (HTTP 413).'
  if (status === 429) return 'Слишком много запросов — попробуйте через несколько секунд.'
  if (status >= 500) return `Внутренняя ошибка сервера (HTTP ${status}).`
  return `Ошибка запроса (HTTP ${status}).`
}

/**
 * Описание для случая, когда fetch отклонился и ответа не было вовсе:
 * нет сети, не резолвится хост, запрос заблокирован браузером.
 * Это единственный случай, который действительно стоит звать сетевой ошибкой.
 */
export function describeNetworkFailure(error: unknown): string {
  const detail = error instanceof Error && error.message ? ` (${error.message})` : ''
  return `Не удалось связаться с сервером${detail}. Проверьте сеть и доступность CMS.`
}
