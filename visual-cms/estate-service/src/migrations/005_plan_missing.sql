-- Признак «в CRM планировки нет».
--
-- Без него невозможно отличить две разные ситуации у квартиры без привязки
-- к типу:
--   а) CRM честно ответила, что чертежа нет — опрашивать больше незачем;
--   б) связь потерялась на нашей стороне — опросить надо обязательно.
--
-- Отметка planProbedAt говорит только «мы ходили», и после потери связей все
-- 144 квартиры дома 5139395 остались навсегда без планировки: отбор на опрос
-- их пропускал, потому что формально они опрошены.

ALTER TABLE apartments
  ADD COLUMN IF NOT EXISTS "planMissing" boolean NOT NULL DEFAULT false;
