-- Настройка склейки типов планировок для витрины.
--
-- MacroCRM отдаёт отдельный чертёж на каждое положение квартиры на этаже, и
-- зеркальные варианты одной планировки попадали в каталог разными карточками:
-- у Doʼstlik до семи штук с одинаковым заголовком, площадью и ценой.
--
-- Правило хранится у каждого ЖК, а не в коде: общего признака «одна
-- планировка» в метаданных нет. Имена планировок у проектов разные («13» и
-- «3_13» против «К1-39.31-6»), а допустимый разброс площади у каждого свой.
--
-- Форма значения (все поля необязательны):
--   {
--     "areaTolerance": 0.25,
--     "groups": [ { "plans": ["К1-39.31-6", "К1-39.3-6"] } ],
--     "keepSeparate": ["К1-42.21-3"]
--   }
--
-- NULL и {} — склеивать только точные совпадения площади.

ALTER TABLE complexes
  ADD COLUMN IF NOT EXISTS "planGrouping" jsonb;
